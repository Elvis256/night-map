// Writes lib/api-zod/src/index.ts with explicit type re-exports so that TS type
// names generated for query params never collide with the zod path-param schemas
// of the same name (both are named `${OperationId}Params`).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "api-zod", "src");
const typesDir = path.join(root, "generated", "types");
const zodSource = readFileSync(path.join(root, "generated", "api.ts"), "utf8");
const zodNames = new Set([...zodSource.matchAll(/^export const (\w+)/gm)].map((m) => m[1]));

const typeNames = [];
for (const file of readdirSync(typesDir)) {
  if (!file.endsWith(".ts") || file === "index.ts") continue;
  const src = readFileSync(path.join(typesDir, file), "utf8");
  for (const m of src.matchAll(/^export (?:interface|type) (\w+)/gm)) {
    if (!zodNames.has(m[1])) typeNames.push(m[1]);
  }
}
typeNames.sort();
const out = `// Generated by scripts/write-zod-index.mjs — do not edit manually.\nexport * from "./generated/api";\nexport type {\n${typeNames.map((n) => `  ${n},`).join("\n")}\n} from "./generated/types";\n`;
writeFileSync(path.join(root, "index.ts"), out);
console.log(`api-zod index: ${typeNames.length} types re-exported`);
